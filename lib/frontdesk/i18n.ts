export type FrontdeskDict = typeof en;

const DICTS: Record<FrontdeskLocale, FrontdeskDict> = { en, nl };

export function fdDict(locale: string | null | undefined): FrontdeskDict {
  return DICTS[locale === "en" ? "en" : "nl"];
}
